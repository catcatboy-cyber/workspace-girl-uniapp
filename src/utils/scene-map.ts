/** 翻译 scene 值：数字场景值返回中文说明；自定义字符串或未知值返回 null */
export function translateSceneLabel(scene?: string | null): string | null {
  if (!scene) return null
  const key = String(scene).trim()
  if (!/^\d+$/.test(key)) return null // 非数字（自定义渠道值）不翻译
  return SCENE_LABELS[key] || null
}

/** 组合来源说明：scene 翻译 + channel/ref 原文，返回展示用字符串 */
export function buildLandingSourceText(
  channel?: string | null,
  scene?: string | null,
  ref?: string | null
): string {
  const parts: string[] = []
  const sceneKey = String(scene || '').trim()
  if (sceneKey) {
    const label = translateSceneLabel(sceneKey)
    parts.push(label ? `${sceneKey} · ${label}` : `${sceneKey} · 未知场景`)
  }
  const channelKey = String(channel || '').trim()
  if (channelKey) parts.push(`渠道 ${channelKey}`)
  const refKey = String(ref || '').trim()
  if (refKey) parts.push(`落地页 ${refKey}`)
  return parts.join(' · ')
}
