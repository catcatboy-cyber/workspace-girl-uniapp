def is_good_day_for_love(officer: str, day_zhi: str, month_zhi: str) -> dict:
    """
    判定当天是否适合感情事项。
    officer: 建除十二神简称
    day_zhi: 当日地支
    month_zhi: 当月月建地支
    """
    quality = day_quality_assessment(officer)
    yiji = daily_yiji_by_officer(officer)

    # 是否适合嫁娶
    jiaqu_ok = "嫁娶" in yiji["yi"]

    # 是否天喜日（日支与月建六合）
    LIUHE = {"子": "丑", "丑": "子", "寅": "亥", "亥": "寅",
             "卯": "戌", "戌": "卯", "辰": "酉", "酉": "辰",
             "巳": "申", "申": "巳", "午": "未", "未": "午"}
    is_tianxi = LIUHE.get(day_zhi) == month_zhi

    love_score = 0
    reasons = []

    if officer in ["成", "开", "满"]:
        love_score += 3
        reasons.append(f"{officer}日为大吉之日，宜嫁娶纳采")
    elif officer in ["定"]:
        love_score += 2
        reasons.append("定日宜订婚签约")
    elif officer in ["破", "闭"]:
        love_score -= 3
        reasons.append(f"{officer}日为大凶，不宜感情大事")

    if is_tianxi:
        love_score += 2
        reasons.append("今日为天喜日（日支与月建六合），感情能量最强")

    if "嫁娶" in yiji["yi"]:
        love_score += 1

    rating = "极佳" if love_score >= 5 else "良好" if love_score >= 3 else \
             "一般" if love_score >= 1 else "不宜" if love_score <= -2 else "平平"

    return {
        "quality": quality,
        "love_score": love_score,
        "love_rating": rating,
        "reasons": reasons,
        "yi_for_love": [y for y in yiji["yi"] if y in
                        ["嫁娶", "纳采", "出行", "会友", "订婚", "安床", "立约"]],
        "ji_for_love": [j for j in yiji["ji"] if j in
                        ["嫁娶", "出行", "入宅"]],
        "tianxi_day": is_tianxi,
    }
