def jianchu_12_day_officer(lunar_month: int, day_zhi: str) -> dict:
    """
    计算建除十二神。
    规则：月建起建日（正月建寅，寅日为建日，卯日为除日...顺排）
    输入：农历月份(1-12), 当日地支
    """
    jian_zhi = MONTH_JIAN.get(lunar_month, "寅")
    jian_idx = DIZHI.index(jian_zhi)
    day_idx = DIZHI.index(day_zhi)
    # 建日=月建所在日，然后顺排
    offset = (day_idx - jian_idx) % 12
    short, full, desc = JIANCHU_12[offset]
    return {
        "short": short,
        "full": full,
        "description": desc,
        "index": offset,
    }


